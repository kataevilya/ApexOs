#ifndef APEXOS_MM_LAYOUT_H
#define APEXOS_MM_LAYOUT_H

/*
 * Единственный источник истины на размер статически замапленных в
 * boot.S 2 MiB huge pages (identity + higher-half). Общий между
 * ассемблером (boot.S компилируется через gcc -c, значит C
 * препроцессор работает и там) и C (vmm.c) — чтобы эти два места
 * не могли молча разойтись, если кто-то поменяет одно и забудет
 * другое.
 *
 * 512 записей = 1 GiB. Раньше здесь было 32 (64 MiB) — этого хватало
 * в QEMU с его идеализированной картой памяти, но НЕ хватало на
 * реальном железе: настоящая прошивка резервирует под себя куда
 * больше памяти в первых мегабайтах (ACPI, SMM, video BIOS shadow),
 * а backbuffer реального экрана высокого разрешения — это уже многие
 * мегабайты сам по себе. 64 MiB суммарно (ramdisk 8 MiB + backbuffer
 * + kheap + служебные структуры) оказалось мало, и наш собственный
 * защитный panic() в vmm.c (специально написанный вместо тихой порчи
 * памяти) на этом и срабатывал. 512 записей — максимум, который влезает
 * в одну PD-таблицу (уже выделена статически в boot.S), поэтому это
 * увеличение бесплатное с точки зрения кода — просто больше записей
 * в уже существующем цикле заполнения PD_low/PD_high.
 */
#define APEXOS_STATIC_MAP_HUGE_PAGES 512
#define APEXOS_STATIC_MAP_BYTES (APEXOS_STATIC_MAP_HUGE_PAGES * 0x200000)

#endif /* APEXOS_MM_LAYOUT_H */
