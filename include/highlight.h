#ifndef APEXOS_HIGHLIGHT_H
#define APEXOS_HIGHLIGHT_H

/*
 * Простая построчная подсветка синтаксиса C-подобного текста для
 * console.c (цвет) + serial (обычный текст, без цвета — serial не
 * поддерживает ANSI-цвета в нашей реализации, и делать это не входит
 * в план: цвет только на экране).
 *
 * Честные ограничения:
 *   - Один токенайзер на C/C++-подобный синтаксис (keywords общие для
 *     обоих, отдельного режима под другие языки нет).
 *   - Блочные комментарии (звёздочка-слэш открывает/закрывает)
 *     отслеживаются МЕЖДУ строками через struct highlight_state — но
 *     экранирование внутри строковых литералов учитывается только
 *     простым способом (обратный слэш перед кавычкой), без полной
 *     обработки всех escape-последовательностей C.
 */

struct highlight_state {
    int in_block_comment;
};

/* Вычисляет палитру через fb_make_color() — вызвать один раз в main.c
   после fb_init()/console_init(). Безопасно вызывать даже без
   доступного экрана. */
void highlight_init(void);

void highlight_state_reset(struct highlight_state *st);

/* Печатает одну строку (без завершающего '\n' — вызывающий код сам
   решает, добавлять ли перевод строки) с подсветкой в консоль и как
   обычный текст в serial. Обновляет *st для следующей строки (учёт
   блочных комментариев, начавшихся, но не закончившихся в этой строке). */
void highlight_print_c_line(struct highlight_state *st, const char *line);

#endif /* APEXOS_HIGHLIGHT_H */
