#ifndef APEXOS_TINYC_H
#define APEXOS_TINYC_H

/*
 * tinyc — маленький ОРИГИНАЛЬНЫЙ интерпретатор C-подобного подмножества,
 * написанный с нуля для ApexOS. ЭТО НЕ TCC И НЕ РЕАЛЬНЫЙ КОМПИЛЯТОР C:
 *   - интерпретируется построчно (обходом токенов), не компилируется в
 *     машинный код;
 *   - единственный тип — int;
 *   - нет функций (кроме встроенного print), массивов, указателей,
 *     структур, #include/#define;
 *   - поддержано: int-переменные, арифметика (+ - * / %), сравнения,
 *     && || !, if/else, while, print("строка") / print(выражение).
 *
 * Названо честно как "tiny C-подобный интерпретатор", чтобы не выдавать
 * себя за настоящий TCC (Tiny C Compiler) — это два разных проекта.
 */
void tinyc_run(const char *source);

#endif /* APEXOS_TINYC_H */
