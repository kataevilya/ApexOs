#ifndef APEXOS_SHELL_H
#define APEXOS_SHELL_H

/* shell_run: интерактивный REPL. Читает клавиатуру, исполняет команды
   над смонтированным FAT32-томом. НЕ возвращается в обычном смысле —
   либо крутится вечно (обычные команды), либо командой `run` передаёт
   управление в ring3 навсегда (планировщика нет — назад дороги нет,
   это самый последний шаг загрузки). */
__attribute__((noreturn))
void shell_run(void);

#endif /* APEXOS_SHELL_H */
