#ifndef APEXOS_EDITOR_H
#define APEXOS_EDITOR_H

#include <stdint.h>
#include "fat32.h"

/*
 * editor_run: полноэкранный редактор с курсором (стрелки), живой
 * подсветкой синтаксиса (см. highlight.c) и сохранением в FAT32.
 *
 * Управление: стрелки — перемещение, Enter/Backspace/Delete — правка,
 * Ctrl+S — сохранить, Ctrl+X — выйти, Ctrl+R — сохранить и запустить
 * (только если файл уже является валидным ELF64 — компилятора C в
 * ApexOS нет, для .c-файла Ctrl+R честно покажет об этом сообщение,
 * а не попытается притвориться, что скомпилировал).
 *
 * Честные ограничения: без горизонтальной прокрутки (длинные строки
 * обрезаются по ширине экрана при отображении, редактирование за
 * пределами видимой области возможно, но не видно), максимум
 * EDITOR_MAX_LINES строк и EDITOR_MAX_LINE_LEN символов в строке —
 * при превышении лишнее отбрасывается, не заполняет память безгранично.
 */
void editor_run(uint32_t dir_cluster, const char name83[FAT32_NAME_LEN], const char *display_name);

#endif /* APEXOS_EDITOR_H */
