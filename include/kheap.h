#ifndef APEXOS_KHEAP_H
#define APEXOS_KHEAP_H

#include <stddef.h>
#include <stdint.h>

/* kheap_init(): не выделяет память сразу — куча растёт по требованию
   (см. kmalloc), первая же реальная страница мапится при первом
   вызове kmalloc, который не может быть удовлетворён пустым списком. */
void kheap_init(void);

/* Выделяет size байт (выровненных на 16), расширяя кучу новыми
   страницами через vmm_map()+pmm_alloc_frame() по необходимости.
   Возвращает NULL только если размер равен 0 или физическая память
   реально закончилась (pmm_alloc_frame вернул 0) — во всех остальных
   некорректных случаях (переполнение размера, превышение лимита кучи)
   вызывается panic(), т.к. это программная ошибка, а не штатная
   нехватка ресурса. */
void *kmalloc(size_t size);

/* Освобождает блок, ранее полученный от kmalloc, сливая его со
   соседними свободными блоками (по адресу) там, где это возможно.
   panic() при: NULL не проверяется отдельно (kfree(NULL) — no-op,
   как и стандартный free()), двойном освобождении, или повреждённом
   заголовке блока (неверный magic — признак переполнения буфера,
   писавшего до begin данного выделения). */
void kfree(void *ptr);

uint64_t kheap_used_bytes(void);
uint64_t kheap_free_bytes(void);

#endif /* APEXOS_KHEAP_H */
