#ifndef APEXOS_VMM_H
#define APEXOS_VMM_H

#include <stdint.h>

#define VMM_PAGE_SIZE 4096u

/* Флаги финальной PT-записи (что реально видит CPU для этой страницы).
   Промежуточные уровни (PML4/PDPT/PD) VMM всегда делает максимально
   разрешающими (PRESENT|WRITABLE|USER) — реальное ограничение прав
   применяется только на последнем уровне, как это делает большинство
   ОС (иначе пришлось бы пересчитывать права всех промежуточных таблиц
   при каждом новом mapping). */
#define VMM_PRESENT  (1ull << 0)
#define VMM_WRITABLE (1ull << 1)
#define VMM_USER     (1ull << 2)

/*
 * vmm_init(): фиксирует физический адрес уже работающего PML4
 * (boot_pml4 из boot.S) как текущее адресное пространство ядра.
 * Никаких новых таблиц не создаёт — просто берёт то, что уже
 * реально используется CPU, под управление этого модуля.
 */
void vmm_init(void);

/*
 * vmm_map(virt, phys, flags): создаёт отображение 4 KiB страницы,
 * при необходимости выделяя недостающие PDPT/PD/PT через pmm_alloc_frame().
 *
 * ВАЖНО — честное ограничение этого этапа: новые таблицы страниц
 * должны физически попадать в уже статически замапленные 64 MiB из
 * boot.S (APEXOS_STATIC_MAP_BYTES), потому что у нас пока нет
 * прямой карты всей физической памяти (direct/physmap). PMM выделяет
 * фреймы линейным сканом от нулевого, поэтому на практике так и
 * происходит, пока эти 64 MiB не исчерпаны — но если это условие
 * нарушится, vmm_map() честно паникует, а не молча пишет в
 * незамапленную физическую страницу (что привело бы либо к triple
 * fault, либо к порче случайных данных).
 *
 * panic() также происходит при: невыровненных virt/phys, phys==0,
 * попытке замапить 4 KiB поверх уже существующей 2 MiB huge page
 * (статические 64 MiB из boot.S), и повторном mapping уже
 * присутствующей записи (вызывающий код обязан unmap перед remap).
 */
void vmm_map(uint64_t virt, uint64_t phys, uint64_t flags);

/*
 * vmm_unmap(virt): снимает отображение страницы и делает invlpg.
 * Если страница не была замаплена — это тоже panic() (по тем же
 * причинам, что и double-free в PMM: почти всегда программная ошибка
 * вызывающего кода, а не штатная ситуация).
 */
void vmm_unmap(uint64_t virt);

/*
 * vmm_get_phys(virt): возвращает физический адрес страницы, в которую
 * отображён virt (с сохранением смещения внутри страницы), либо 0,
 * если virt не замаплен. 0 однозначно означает "не замаплено" — PMM
 * никогда не выдаёт физический фрейм 0 (он зарезервирован навсегда).
 */
uint64_t vmm_get_phys(uint64_t virt);

#endif /* APEXOS_VMM_H */
