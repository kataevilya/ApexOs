#ifndef APEXOS_RTC_H
#define APEXOS_RTC_H

#include <stdint.h>

struct rtc_time {
    uint8_t second;
    uint8_t minute;
    uint8_t hour;   /* 0-23, уже переведено из 12-часового формата, если он был включён */
    uint8_t day;
    uint8_t month;
    uint16_t year;  /* полный год (напр. 2026), а не смещение от 1900/2000 */
};

/*
 * rtc_read: читает текущее время из CMOS RTC (порты 0x70/0x71),
 * дожидаясь окончания цикла обновления и корректно обрабатывая
 * BCD-кодировку, если она включена (регистр состояния B).
 *
 * Честное ограничение: предполагаем 21-й век (год = 2000 + значение
 * из CMOS) — реальное железо/BIOS обычно так и делают, но формально
 * век CMOS не хранит. Часовой пояс не учитывается (что в CMOS, то и
 * возвращаем — обычно UTC или локальное время BIOS, как настроено).
 */
void rtc_read(struct rtc_time *out);

#endif /* APEXOS_RTC_H */
